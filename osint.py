def extract_metadata(url, body):
    print_section("METADATA & PERSONAL INFO")
    person_data = {}

    if not body:
        print("  [!] No body to analyze.")
        return person_data

    # emails
    emails = list(set(re.findall(r'[\w\.-]+@[\w\.-]+\.\w{2,6}', body)))
    if emails:
        person_data["emails"] = emails
        print(f"  Emails found    : {', '.join(emails[:10])}")

    # phone numbers
    phones = list(set(re.findall(r'[\+\(]?[\d\s\-\(\)]{7,20}[\d]', body)))
    phones = [p.strip() for p in phones if len(re.sub(r'\D','',p)) >= 7][:10]
    if phones:
        person_data["phones"] = phones
        print(f"  Phones found    : {', '.join(phones[:5])}")

    # social media
    socials = {}
    social_patterns = {
        "twitter":   r'twitter\.com/([A-Za-z0-9_]{1,50})',
        "linkedin":  r'linkedin\.com/in/([A-Za-z0-9\-]{1,80})',
        "instagram": r'instagram\.com/([A-Za-z0-9_\.]{1,50})',
        "facebook":  r'facebook\.com/([A-Za-z0-9\.]{1,80})',
        "github":    r'github\.com/([A-Za-z0-9\-]{1,40})',
        "youtube":   r'youtube\.com/(?:c/|channel/|user/)?([A-Za-z0-9_\-]{1,80})',
    }
    for net, pat in social_patterns.items():
        matches = re.findall(pat, body, re.IGNORECASE)
        if matches:
            socials[net] = list(set(matches))
            print(f"  {net:12}: {', '.join(socials[net][:3])}")
    if socials:
        person_data["social_media"] = socials

    # meta tags
    meta_patterns = {
        "author":      r'<meta[^>]+name=["\']author["\'][^>]+content=["\'](.*?)["\']',
        "description": r'<meta[^>]+name=["\']description["\'][^>]+content=["\'](.*?)["\']',
        "keywords":    r'<meta[^>]+name=["\']keywords["\'][^>]+content=["\'](.*?)["\']',
        "og:title":    r'<meta[^>]+property=["\']og:title["\'][^>]+content=["\'](.*?)["\']',
        "og:site_name":r'<meta[^>]+property=["\']og:site_name["\'][^>]+content=["\'](.*?)["\']',
    }
    for key, pat in meta_patterns.items():
        m = re.search(pat, body, re.IGNORECASE | re.DOTALL)
        if m:
            person_data[key] = m.group(1).strip()
            print(f"  {key:16}: {m.group(1).strip()[:80]}")

    # names from body
    name_matches = re.findall(
        r'\b([A-Z][a-z]{2,15})\s([A-Z][a-z]{2,15})\b', body)
    if name_matches:
        names = list(set([f"{a} {b}" for a,b in name_matches]))[:5]
        person_data["possible_names"] = names
        print(f"  Possible names  : {', '.join(names)}")

    # dates / years
    years = list(set(re.findall(r'\b(19[5-9]\d|20[0-2]\d)\b', body)))
    if years:
        person_data["years_found"] = years
        print(f"  Years found     : {', '.join(sorted(years)[:10])}")

    return person_data

