def get_whois(domain):
    print_section("WHOIS INFO")
    if not WHOIS_AVAILABLE:
        print("  [!] whois module not installed. Run: pip install python-whois")
        return {}
    try:
        w = whois.whois(domain)
        info = {}
        fields = ["domain_name","registrar","creation_date","expiration_date",
                  "updated_date","name_servers","status","emails","name","org",
                  "address","city","state","zipcode","country"]
        for f in fields:
            val = getattr(w, f, None)
            if val:
                info[f] = str(val)
                print(f"  {f:20}: {str(val)[:80]}")
        return info
    except Exception as e:
        print(f"  [!] WHOIS error: {e}")
        return {}

