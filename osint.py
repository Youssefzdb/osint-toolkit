def get_http_info(url):
    print_section("HTTP HEADERS & TECH")
    body, headers = safe_get(url)
    if not headers:
        print("  [!] Could not reach the URL.")
        return {}, ""

    interesting = ["Server","X-Powered-By","X-Generator","X-Frame-Options",
                   "Content-Security-Policy","Strict-Transport-Security",
                   "X-Content-Type-Options","Set-Cookie","Location",
                   "X-AspNet-Version","CF-Ray","Via"]
    for h in interesting:
        val = headers.get(h) or headers.get(h.lower())
        if val:
            print(f"  {h:30}: {val[:100]}")

    # CMS detection
    techs = []
    if body:
        patterns = {
            "WordPress": r"wp-content|wp-includes|wordpress",
            "Joomla":    r"joomla",
            "Drupal":    r"drupal",
            "Shopify":   r"shopify",
            "React":     r"react\.js|react-dom|__REACT",
            "Vue.js":    r"vue\.js|vue\.min\.js",
            "Angular":   r"ng-version|angular\.js",
            "Bootstrap": r"bootstrap\.min\.css|bootstrap\.css",
            "jQuery":    r"jquery\.min\.js|jquery-",
        }
        for tech, pat in patterns.items():
            if re.search(pat, body, re.IGNORECASE):
                techs.append(tech)
        if techs:
            print(f"\n  [+] Detected technologies: {', '.join(techs)}")

    return headers, body or ""

