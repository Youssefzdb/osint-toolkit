LEET = {'a':'4','e':'3','i':'1','o':'0','s':'5','t':'7'}

def leet(word):
    result = ""
    for c in word.lower():
        result += LEET.get(c, c)
    return result

def generate_passwords(person_data, domain):
    print_section("GENERATED PASSWORDS (OSINT-BASED)")

    tokens = set()

    # domain name parts
    base_domain = domain.replace("www.","").split(".")[0]
    tokens.add(base_domain)

    # emails → extract name parts
    for email in person_data.get("emails", []):
        local = email.split("@")[0]
        for part in re.split(r'[._\-]', local):
            if len(part) > 2:
                tokens.add(part)

    # possible names
    for full_name in person_data.get("possible_names", []):
        parts = full_name.split()
        for p in parts:
            tokens.add(p.lower())
        tokens.add(full_name.replace(" ","").lower())
        tokens.add(full_name.replace(" ","_").lower())

    # author meta
    author = person_data.get("author","")
    if author:
        for p in author.split():
            tokens.add(p.lower())

    # years
    years = person_data.get("years_found", [])

    # og:title / site_name
    for key in ["og:title","og:site_name","description"]:
        val = person_data.get(key,"")
        if val:
            words = re.findall(r'[A-Za-z]{3,12}', val)
            for w in words[:4]:
                tokens.add(w.lower())

    tokens.discard("")

    suffixes = ["", "123", "1234", "12345", "!", "@", "#", "2024", "2025",
                "2023", "01", "99", "00", "007", "!@#"]
    prefixes = ["", "admin", "pass", "P@ss"]

    passwords = set()

    for tok in list(tokens)[:15]:
        for suf in suffixes[:8]:
            passwords.add(tok + suf)
            passwords.add(tok.capitalize() + suf)
            passwords.add(leet(tok) + suf)
        for pre in prefixes[1:3]:
            passwords.add(pre + tok.capitalize())

        # tok + year combos
        for yr in years[:3]:
            passwords.add(tok + yr)
            passwords.add(tok.capitalize() + yr)

    # domain + year
    for yr in years[:3]:
        passwords.add(base_domain + yr)
        passwords.add(base_domain.capitalize() + yr)

    # sort by likely strength (longer first)
    password_list = sorted(passwords, key=lambda x: -len(x))[:50]

    print(f"\n  Generated {len(password_list)} candidate passwords:\n")
    for i, pw in enumerate(password_list, 1):
        print(f"  {i:3}. {pw}")

    return password_list

