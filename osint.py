def get_dns(domain):
    print_section("DNS RECORDS")
    results = {}
    if DNS_AVAILABLE:
        for rtype in ["A","AAAA","MX","NS","TXT","CNAME","SOA"]:
            try:
                answers = dns.resolver.resolve(domain, rtype)
                vals = [str(r) for r in answers]
                results[rtype] = vals
                print(f"  {rtype:6}: {', '.join(vals)[:100]}")
            except Exception:
                pass
    else:
        # fallback: basic socket
        try:
            ip = socket.gethostbyname(domain)
            results["A"] = [ip]
            print(f"  A     : {ip}")
        except Exception as e:
            print(f"  [!] DNS error: {e}")
    return results

