    report = {
        "target": domain,
        "date": datetime.now().isoformat(),
        "whois": whois_data,
        "dns": dns_data,
        "metadata": person_data,
        "generated_passwords": passwords,
    }
    with open(filename, "w") as f:
        json.dump(report, f, indent=2, default=str)
    print(f"\n  [+] Report saved to: {filename}")
    return filename

